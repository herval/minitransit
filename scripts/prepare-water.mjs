import {readFile,writeFile} from 'node:fs/promises';

// Keep shoreline data in the image: browsers never query Census or a map service.
const source='https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/Hydro/MapServer/1';
const bounds=[-123.15,36.9,-121.45,38.65],tolerance=.0001;
const query=new URLSearchParams({f:'geojson',where:"MTFCC = 'H2051' OR NAME LIKE '%Merritt%'",geometry:bounds.join(','),geometryType:'esriGeometryEnvelope',inSR:'4326',spatialRel:'esriSpatialRelIntersects',outFields:'NAME,MTFCC',returnGeometry:'true',outSR:'4326',maxAllowableOffset:'0.00005',geometryPrecision:'5'});

// Clip each filled ring against the region's rectangle, including island rings.
function clip(ring){
 let points=ring.slice(0,-1);
 for(const [axis,limit,sign] of [[0,bounds[0],1],[0,bounds[2],-1],[1,bounds[1],1],[1,bounds[3],-1]]){
  const result=[];
  for(let i=0;i<points.length;i++){
   const a=points[(i+points.length-1)%points.length],b=points[i];
   const ain=(a[axis]-limit)*sign>=0,bin=(b[axis]-limit)*sign>=0;
   if(ain!==bin){const fraction=(limit-a[axis])/(b[axis]-a[axis]);result.push([a[0]+fraction*(b[0]-a[0]),a[1]+fraction*(b[1]-a[1])]);}
   if(bin)result.push(b);
  }
  points=result;if(!points.length)return [];
 }
 points=points.map(point=>point.map(value=>Math.round(value*1e5)/1e5)).filter((point,i,all)=>!i||point[0]!==all[i-1][0]||point[1]!==all[i-1][1]);
 if(points.length&&points[0].some((value,i)=>value!==points.at(-1)[i]))points.push(points[0]);
 return points;
}
function distanceSquared(point,a,b){
 const dx=b[0]-a[0],dy=b[1]-a[1],length=dx*dx+dy*dy;
 const fraction=length?Math.max(0,Math.min(1,((point[0]-a[0])*dx+(point[1]-a[1])*dy)/length)):0;
 return (point[0]-a[0]-fraction*dx)**2+(point[1]-a[1]-fraction*dy)**2;
}
function simplify(points){
 if(points.length<4)return [];
 const keep=new Set([0,points.length-1]),stack=[[0,points.length-1]];
 while(stack.length){
  const [from,to]=stack.pop();let furthest=-1,maximum=tolerance*tolerance;
  for(let i=from+1;i<to;i++){const distance=distanceSquared(points[i],points[from],points[to]);if(distance>maximum){maximum=distance;furthest=i;}}
  if(furthest!==-1){keep.add(furthest);stack.push([from,furthest],[furthest,to]);}
 }
 return points.filter((_,i)=>keep.has(i));
}
function area(ring){return ring.reduce((sum,point,i)=>{const next=ring[(i+1)%ring.length];return sum+point[0]*next[1]-next[0]*point[1];},0)/2;}

let data;
if(process.argv[2])data=JSON.parse(await readFile(process.argv[2],'utf8'));
else{
 const response=await fetch(source+'/query?'+query,{signal:AbortSignal.timeout(60000)});
 if(!response.ok)throw Error('Census shoreline returned '+response.status);
 data=await response.json();
}
if(data.error||data.exceededTransferLimit||!data.features?.length)throw Error('Incomplete shoreline extract');
const polygons=[];
for(const feature of data.features){
 if(feature.properties.MTFCC!=='H2051'&&!/Merritt/i.test(feature.properties.NAME||''))continue;
 const pieces=feature.geometry?.type==='Polygon'?[feature.geometry.coordinates]:feature.geometry?.type==='MultiPolygon'?feature.geometry.coordinates:[];
 for(const piece of pieces){
  const rings=[];
  for(let i=0;i<piece.length;i++){
   const ring=simplify(clip(piece[i]));
   if(ring.length<4||Math.abs(area(ring))<1e-10){if(!i)break;continue;}
   // One compound SVG path can combine water polygons without turning their
   // overlaps into land. Island holes wind in the opposite direction.
   if((area(ring)>0)!==(i===0))ring.reverse();
   rings.push(ring);
  }
  if(rings.length)polygons.push(rings);
 }
}
if(!polygons.length)throw Error('No shoreline polygons remain');
const metadata={source:'U.S. Census Bureau TIGERweb Areal Hydrography',url:source,bounds,toleranceDegrees:tolerance};
const output='// Generated by scripts/prepare-water.mjs. Longitude/latitude; outer rings then island holes.\nexport const WATER_SOURCE='+JSON.stringify(metadata)+';\nexport const WATER_POLYGONS='+JSON.stringify(polygons)+';\n';
await writeFile(new URL('../public/water-data.js',import.meta.url),output);
console.log(JSON.stringify({polygons:polygons.length,vertices:polygons.flat(2).length,bytes:Buffer.byteLength(output)}));
